export const validators = {
  // first_name, second_name — латиница или кириллица, первая заглавная,
  // без пробелов и цифр, из спецсимволов только дефис
  name: (v: string) =>
    /^[A-ZА-ЯЁ][a-zA-Zа-яёА-ЯЁ]*(?:-[A-ZА-ЯЁ][a-zA-Zа-яёА-ЯЁ]*)*$/.test(v)
      ? null
      : 'Латиница или кириллица, первая заглавная, без пробелов и цифр, только дефис',

  // login — 3–20 символов, латиница, цифры, дефис, подчёркивание;
  // не состоит только из цифр; без пробелов
  login: (v: string) =>
    /^(?=.*[a-zA-Z])[a-zA-Z0-9_-]{3,20}$/.test(v)
      ? null
      : '3–20 символов, латиница, цифры, - и _, не только цифры',

  // email — латиница, цифры, спецсимволы; обязательны @ и точка после неё;
  // между @ и точкой — буквы
  email: (v: string) =>
    /^[a-zA-Z0-9._%+-]+@[a-zA-Z]+\.[a-zA-Z]{2,}$/.test(v)
      ? null
      : 'Некорректный email',

  // password — 8–40 символов, минимум одна заглавная и одна цифра
  password: (v: string) =>
    /^(?=.*[A-ZА-ЯЁ])(?=.*\d).{8,40}$/.test(v)
      ? null
      : '8–40 символов, минимум одна заглавная буква и одна цифра',

  // phone — 10–15 символов, цифры, может начинаться с плюса
  phone: (v: string) =>
    /^\+?\d{10,15}$/.test(v)
      ? null
      : '10–15 цифр, может начинаться с +',

  // message — не пустое
  message: (v: string) =>
    v.trim().length > 0
      ? null
      : 'Сообщение не должно быть пустым',
} as const;

export type ValidatorName = keyof typeof validators;

